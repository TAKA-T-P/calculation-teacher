const ROOT = path.join(__dirname, '..', '..', '..');
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'manifest.json'), 'utf8'));
const done = new Set();
for (const f of manifest.files) {
  const p = path.join(ROOT, 'data', f.file);
  const data = JSON.parse(fs.readFileSync(p, 'utf8'));
  let changed = false;
  data.questions.forEach((q) => {
    if (HINTS[q.id] && q.hint !== HINTS[q.id]) { q.hint = HINTS[q.id]; changed = true; }
    if (HINTS[q.id]) done.add(q.id);
  });
  if (changed) fs.writeFileSync(p, `${JSON.stringify(data, null, 2)}\n`);
}
const missing = Object.keys(HINTS).filter((id) => !done.has(id));
if (missing.length) { console.error(`見つからない問題: ${missing.join(', ')}`); process.exit(1); }
console.log(`ヒントを直しました: ${done.size}問`);
